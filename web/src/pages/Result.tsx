import { useMemo } from "react";
import { Link, useParams } from "react-router";
import { api } from "../data/source";
import type { ResultDetail } from "../data/types";
import { useApi } from "../data/useApi";
import { AXIS, EChart, TOOLTIP, type EOption } from "../components/EChart";
import { Chip, Loading, Panel, RecordLink, Stat } from "../components/ui";
import { fix1, pct, wordTone } from "../components/format";

const STAGE_HINT: Record<string, string> = {
  Templates: "Which refinement steps the kernel is built from",
  Assignment: "The values the solver chose for the family's variables",
  Prediction: "What the performance model expected before compiling",
  Build: "Compiler feedback: registers, spills, shared memory",
  "SASS check": "The intended instructions really appear in the binary",
  Correctness: "Numerical checks over input distributions, including hidden edge shapes",
  Measurement: "Timed under the frozen measurement protocol",
  "Gap to bound": "How far from the theoretical lower bound, and why",
};

export function ResultPage() {
  const { id = "" } = useParams();
  const r = useApi(() => api.lineage(id), [id]);
  if (!r.data) return <Loading error={r.error} />;
  return <ResultBody r={r.data} />;
}

function ResultBody({ r }: { r: ResultDetail }) {
  return (
    <div className="stack">
      <div className="case-head">
        <div>
          <div className="caption">Result · Solution record</div>
          <h2 style={{ fontSize: 20 }}><Link to={`/cases/${r.case_id}`} className="mono">{r.case_name}</Link> <span className="ink2" style={{ fontWeight: 400 }}>· {r.bucket}</span></h2>
          <div className="ink2">built from <Link to={`/families/${r.family}`} className="mono">{r.family_name}</Link> · <RecordLink id={r.id} label="solution record" /></div>
        </div>
      </div>
      <div className="verdict">{r.verdict ?? "No judgement record references this Solution."}</div>
      {r.missing.length > 0 && <div className="missing">Missing links in the evidence chain: {r.missing.join(", ")}. A result with missing links is not trustworthy.</div>}
      {r.pct_of_bound > 0.95 && (
        <div className="inbox-callout">
          <span className="badge human">!</span>
          <span>This result is above 95% of the lower bound, which can mean a measurement or checking problem; docs/design/30 §2 asks for re-verification. (The inbox item for this trigger is generated by WP6, not yet active.)</span>
        </div>
      )}
      <div className="grid" style={{ gridTemplateColumns: "minmax(0, 1.25fr) minmax(0, 1fr)", alignItems: "start" }}>
        <Panel primary title="Evidence chain" sub="read top to bottom: each link is a record produced by a tool or checker, never by the agent's own claim">
          <ol className="chain">
            {r.chain.map((l, i) => (
              <li key={l.stage} className="chain-link">
                <div className="chain-rail"><span className="chain-dot">{i + 1}</span></div>
                <div className="chain-card">
                  <div className="row">
                    <b>{l.stage}</b>
                    <span className="small muted">{STAGE_HINT[l.stage]}</span>
                    <span style={{ marginLeft: "auto" }} className="row">
                      {l.status && <Chip tone={wordTone(l.status)}>{l.status}</Chip>}
                      <RecordLink id={l.record} />
                    </span>
                  </div>
                  <div className="chain-fact">{l.fact}</div>
                  <div className="small muted">{l.title}</div>
                </div>
              </li>
            ))}
          </ol>
        </Panel>
        <div className="stack">
          <div className="stats" style={{ gridTemplateColumns: "1fr 1fr" }}>
            <Stat label="Measured" value={fix1(r.measured_us)} unit="µs" record={r.chain.find((l) => l.stage === "Measurement")?.record} />
            <Stat label="% of bound" value={pct(r.pct_of_bound)} foot={`bound ${fix1(r.bound_us)} µs`} record={r.chain.find((l) => l.stage === "Gap to bound")?.record} />
          </div>
          <Panel title="Gap decomposition per hardware unit" sub="bound vs predicted vs measured time on each unit">
            <UnitChart r={r} />
            {r.explained_share == null ? <div className="small muted">No judgement record states how much of the gap is explained.</div> : (
            <div className="explained">
              <div className="small ink2">Gap to bound explained by the model</div>
              <div className="bar" style={{ height: 12 }}>
                <span className="used" style={{ width: `${r.explained_share * 100}%`, background: "var(--st-ok)" }} />
              </div>
              <div className="row small"><span>{pct(r.explained_share)} explained</span><span className="muted" style={{ marginLeft: "auto" }}>{pct(1 - r.explained_share)} unexplained</span></div>
            </div>)}
          </Panel>
          <details className="panel" style={{ padding: "4px 12px" }}>
            <summary>Why each link is required (docs/design/30 §1)</summary>
            <p className="small ink2">A result is only trusted when every link exists as a record with origin <span className="mono">real</span>. Agents can propose; only checkers write
              correctness and SASS verdicts, and only the measure tool writes measurements. A missing or stale link makes the result stale.</p>
          </details>
        </div>
      </div>
    </div>
  );
}

function UnitChart({ r }: { r: ResultDetail }) {
  const option = useMemo<EOption>(() => ({
    animation: false,
    grid: { left: 60, right: 40, top: 30, bottom: 24 },
    legend: { top: 0, textStyle: { color: "#52514e", fontSize: 11 }, itemWidth: 12, itemHeight: 10 },
    tooltip: { ...TOOLTIP, trigger: "axis", axisPointer: { type: "shadow" }, valueFormatter: (v: number) => `${v} µs` },
    xAxis: { type: "value", name: "µs", ...AXIS },
    yAxis: { type: "category", data: r.units.map((u) => u.unit), ...AXIS, axisTick: { show: false } },
    series: [
      { name: "bound", color: "#c3c2b7", key: "bound_us" as const },
      { name: "predicted", color: "#a79cf0", key: "predicted_us" as const },
      { name: "measured", color: "#2a78d6", key: "measured_us" as const },
    ].map((s) => ({ type: "bar", name: s.name, data: r.units.map((u) => u[s.key]), itemStyle: { color: s.color, borderRadius: [0, 4, 4, 0] }, barMaxWidth: 12, barGap: "25%" })),
  }) as EOption, [r]);
  return <EChart option={option} height={Math.max(150, r.units.length * 64 + 50)} />;
}
